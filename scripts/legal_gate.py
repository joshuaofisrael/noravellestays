def collapse(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def snippet(text: str, start: int, end: int, pad: int = 80) -> str:
    left = max(0, start - pad)
    right = min(len(text), end + pad)
    chunk = text[left:right].strip()
    if left > 0:
        chunk = "..." + chunk
    if right < len(text):
        chunk = chunk + "..."
    return chunk[:500]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def publication_state(rel: str) -> str:
    rel = rel.replace("\\", "/").lstrip("./")
    if rel.startswith(".") or rel.startswith(SKIP_PREFIXES):
        return "skip"
    if rel.startswith(UNPUBLISHED_PREFIXES):
        return "unpublished"
    return "published"


def norm_repo_path(path: str) -> str:
    parts: list[str] = []
    for part in path.replace("\\", "/").split("/"):
        if part in ("", "."):
            continue
        if part == "..":
            if parts:
                parts.pop()
            continue
        parts.append(part)
    return "/".join(parts)


def resolve_src(src: str, page_rel: str) -> str:
    raw = src.strip()
    if not raw or raw.lower().startswith("data:"):
        return raw
    bare = raw.split("#", 1)[0].split("?", 1)[0]
    if bare.startswith("//"):
        return "https:" + bare
    if bare.lower().startswith(("http://", "https://")):
        parsed = urlparse(bare)
        host = (parsed.hostname or "").lower()
        if host in OWN_HOSTS or host.endswith(".noravellestays.com"):
            return norm_repo_path(parsed.path)
        return bare
    if bare.startswith("/"):
        return norm_repo_path(bare)
    base = page_rel.rsplit("/", 1)[0] if "/" in page_rel else ""
    return norm_repo_path(f"{base}/{bare}" if base else bare)


def is_external_href(href: str) -> bool:
    if not href.lower().startswith(("http://", "https://")):
        return False
    host = (urlparse(href).hostname or "").lower()
    if host in OWN_HOSTS or host.endswith(".noravellestays.com"):
        return False
    return True


def is_decorative(attrs: dict[str, str]) -> bool:
    """Explicit decorative markup. A missing alt is not treated as decorative."""
    role = attrs.get("role", "").lower()
    aria = attrs.get("aria-hidden", "").lower()
    classes = attrs.get("class", "").lower().split()
    if role in {"presentation", "none"}:
        return True
    if aria in {"true", "1"}:
        return True
    if "decorative" in classes:
        return True
    if "alt" in attrs and attrs.get("alt", "").strip() == "":
        return True
    return False


def image_excepted(src: str, attrs: dict[str, str]) -> bool:
    """Non SVG decorative images are excepted. SVG images are always checked."""
    if not is_decorative(attrs):
        return False
    path = src.split("?", 1)[0].split("#", 1)[0].lower()
    return not path.endswith(".svg")


def negated_before(text: str, start: int) -> bool:
    left = 0
    for mark in ".!?":
        pos = text.rfind(mark, 0, start)
        if pos + 1 > left:
            left = pos + 1
    window = text[left:start][-80:]
    return bool(NEG_RE.search(window))


def election_key(term: str) -> str:
    lowered = term.lower()
    if lowered.startswith("vot"):
        return "vote"
    if lowered.startswith("ballot"):
        return "ballot"
    if lowered.startswith("poll"):
        return "polling"
    return "registration deadline"


def _walk_types(node) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        raw = node.get("@type")
        if isinstance(raw, str):
            found.add(raw)
        elif isinstance(raw, list):
            found.update(item for item in raw if isinstance(item, str))
        for value in node.values():
            found.update(_walk_types(value))
    elif isinstance(node, list):
        for item in node:
            found.update(_walk_types(item))
    return found


def types_from_jsonld(blobs: list[str]) -> set[str]:
    found: set[str] = set()
    for blob in blobs:
        try:
            data = json.loads(blob)
        except json.JSONDecodeError:
            found.update(re.findall(r'"@type"\s*:\s*"([^"]+)"', blob))
            continue
        found.update(_walk_types(data))
    return found


class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.title_parts: list[str] = []
        self.in_title = False
        self.skip_depth = 0
        self.in_jsonld = False
        self.jsonld_parts: list[str] = []
        self.text_parts: list[str] = []
        self.imgs: list[dict[str, str]] = []
        self.hrefs: list[str] = []
        self.metas: list[dict[str, str]] = []
        self.factual_marker = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attr = {key.lower(): (value or "") for key, value in attrs}
        if tag in {"p", "div", "li", "h1", "h2", "h3", "h4", "br", "tr", "section", "article"}:
            self.text_parts.append("\n")
        if tag == "title":
            self.in_title = True
        if tag == "meta":
            self.metas.append(attr)
        if tag == "img":
            self.imgs.append(attr)
        if tag == "a" and attr.get("href"):
            self.hrefs.append(attr["href"])
        for name in ("class", "id"):
            if SECTION_MARKER.search(attr.get(name, "")):
                self.factual_marker = True
        if tag == "script":
            if "ld+json" in attr.get("type", "").lower():
                self.in_jsonld = True
                self.jsonld_parts.append("")
            else:
                self.skip_depth += 1
        elif tag == "style":
            self.skip_depth += 1

    def handle_endtag(self, tag: str) -> None:
        if tag == "title":
            self.in_title = False
        if tag == "script" and self.in_jsonld:
            self.in_jsonld = False
        elif tag == "script" and self.skip_depth:
            self.skip_depth -= 1
        elif tag == "style" and self.skip_depth:
            self.skip_depth -= 1

    def handle_data(self, data: str) -> None:
        if self.in_title:
            self.title_parts.append(data)
        if self.in_jsonld:
            self.jsonld_parts[-1] += data
            return
        if self.skip_depth:
            return
        self.text_parts.append(data)


def meta_content(metas: list[dict[str, str]], name: str) -> str:
    for item in metas:
        if item.get("name", "").lower() == name.lower():
            return item.get("content", "")
    return ""


def caption_after(html: str, index: int) -> str:
    """Caption means the next figcaption or mood caption, not the following prose."""
    matches = list(re.finditer(r"<img\b[^>]*>", html, flags=re.I))
    if index >= len(matches):
        return ""
    tail = html[matches[index].end(): matches[index].end() + 800]
    match = re.match(
        r"\s*(?:<figcaption[^>]*>(.*?)</figcaption>|"
        r"<p[^>]*class=\"[^\"]*mood-caption[^\"]*\"[^>]*>(.*?)</p>)",
        tail,
        flags=re.I | re.S,
    )
    if not match:
        return ""
    raw = match.group(1) if match.group(1) is not None else match.group(2)
    raw = re.sub(r"<[^>]+>", " ", raw or "")
    return collapse(raw)[:300]


def nearest_name(text: str, keyword_span: tuple[int, int]) -> tuple[int, int, str] | None:
    names: list[tuple[int, int, str]] = []
    for regex in (NAME_RE, HOTEL_RE):
        for match in regex.finditer(text):
            names.append((match.start(), match.end(), collapse(match.group(0))))
    best: tuple[int, int, int, int, str] | None = None
    k0, k1 = keyword_span
    for start, end, name in names:
        if start < k1 and end > k0:
            continue
        distance = (k0 - end) if end <= k0 else (start - k1)
        if distance > NAME_LIMIT:
            continue
        candidate = (distance, -len(name), start, end, name)
        if best is None or candidate < best:
            best = candidate
    if best is None:
        return None
    return best[2], best[3], best[4]


def manifest_index(manifest: dict) -> dict[str, dict]:
    index: dict[str, dict] = {}
    for entry in manifest.get("images", []):
        if isinstance(entry, dict) and entry.get("path"):
            index[norm_repo_path(str(entry["path"]))] = entry
    return index


def licence_publishes(entry: dict | None) -> bool:
    if not entry:
        return False
    if str(entry.get("status", "")).upper() == "HOLD":
        return False
    return bool(str(entry.get("licence") or "").strip())


def analyze_html(html: str, rel: str, manifest: dict) -> tuple[list[Finding], list[Note]]:
    """Return findings and suppressed phrase notes for one HTML document."""
    rel = rel.replace("\\", "/").lstrip("./")
    parser = PageParser()
    parser.feed(html)
    parser.close()
    title = collapse(" ".join(parser.title_parts)) or rel
    description = meta_content(parser.metas, "description")
    visible = collapse(" ".join(parser.text_parts))
    chunks = [chunk for chunk in (title, description, visible) if chunk]
    types = types_from_jsonld(parser.jsonld_parts)
    for blob in parser.jsonld_parts:
        text = collapse(blob)
        if text:
            chunks.append(text)
    sources = []
    seen_sources: set[str] = set()
    for href in parser.hrefs:
        if is_external_href(href) and href not in seen_sources:
            seen_sources.add(href)
            sources.append(href)
    published = publication_state(rel) == "published"
    findings: list[Finding] = []
    notes: list[Note] = []
    seen: set[tuple[str, str]] = set()

    def add(rule: str, key: str, flagged: str, force_block: bool = False) -> None:
        marker = (rule, key)
        if marker in seen:
            return
        seen.add(marker)
        findings.append(
            Finding(
                path=rel,
                rule=rule,
                key=key,
                flagged=flagged[:500],
                suggestion=SUGGESTIONS[rule],
                sources=sources[:12],
                title=title[:300],
                published=published,
                force_block=force_block,
            )
        )

    review = meta_content(parser.metas, "review-status").strip()
    under_drafts = rel.startswith("drafts/")
    if review == "HOLD_REVIEW" or under_drafts:
        why = "meta review-status HOLD_REVIEW" if review == "HOLD_REVIEW" else "path under drafts/"
        if review == "HOLD_REVIEW" and under_drafts:
            why = "meta review-status HOLD_REVIEW and path under drafts/"
        add("HOLD_REVIEW", "marker", why)

    for chunk in chunks:
        for match in R1_RE.finditer(chunk):
            picked = nearest_name(chunk, (match.start(), match.end()))
            if not picked:
                continue
            _start, _end, name = picked
            keyword = match.group(0).lower()
            if keyword.endswith("s") and keyword[:-1] in {"fraud", "lawsuit", "scam"}:
                keyword = keyword[:-1]
            left = min(match.start(), _start)
            right = max(match.end(), _end)
            add("1", f"{keyword}|{name}", snippet(chunk, left, right))
        occupied: list[tuple[int, int]] = []
        lower = chunk.lower()
        for phrase in (*ENDORSEMENT, *GUIDANCE):
            rule = "5" if phrase in GUIDANCE else "7"
            start = 0
            while True:
                found = lower.find(phrase, start)
                if found < 0:
                    break
                end = found + len(phrase)
                start = end
                if any(bound_start <= found and end <= bound_end for bound_start, bound_end in occupied):
                    continue
                occupied.append((found, end))
                if negated_before(chunk, found):
                    if not any(note.path == rel and note.phrase == phrase for note in notes):
                        notes.append(Note(rel, phrase, snippet(chunk, found, end)))
                else:
                    add(rule, phrase, snippet(chunk, found, end))
        for match in ELECTION_RE.finditer(chunk):
            key = election_key(match.group(0))
            add("6", key, snippet(chunk, match.start(), match.end()))

    factual = bool(types & FACTUAL_TYPES) or parser.factual_marker
    if factual and not sources:
        label = ", ".join(sorted(types & FACTUAL_TYPES)) or "factual section"
        add("4", "missing-external-source", f"No off site source URL ({label}).")

    index = manifest_index(manifest)
    for img_i, attrs in enumerate(parser.imgs):
        raw_srcs = []
        if attrs.get("src"):
            raw_srcs.append(attrs["src"])
        raw_srcs.extend(part.strip().split()[0] for part in attrs.get("srcset", "").split(",") if part.strip())
        alt = attrs.get("alt", "")
        caption = caption_after(html, img_i)
        for raw in raw_srcs:
            if image_excepted(raw, attrs):
                continue
            if raw.lower().startswith("data:"):
                add("3", "data-uri", "Inline data URI image has no licence manifest entry.")
                continue
            resolved = resolve_src(raw, rel)
            entry = index.get(resolved) if not resolved.lower().startswith(("http://", "https://")) else index.get(resolved)
            if resolved.lower().startswith(("http://", "https://")):
                entry = index.get(resolved)
            if not licence_publishes(entry):
                state = "missing from the manifest" if entry is None else "manifest status HOLD"
                add("3", resolved, f"{resolved} ({state}).")
            blob = f"{alt} {caption}"
            synthetic = bool(entry and entry.get("synthetic") is True) or bool(AI_RE.search(blob))
            if synthetic and "illustrative" not in blob.lower():
                add("7", f"ai:{resolved}", f"{resolved} is marked synthetic or AI and has no illustrative caption.")

    return findings, notes


def load_json(path: Path, fallback):
    if not path.is_file():
        return fallback
    return json.loads(path.read_text(encoding="utf-8"))


def iter_html(root: Path) -> list[Path]:
    files = []
    for path in root.rglob("*.html"):
        rel = path.relative_to(root).as_posix()
        if publication_state(rel) == "skip":
            continue
        files.append(path)
    return sorted(files)


def image_files(root: Path) -> list[str]:
    found = []
    for folder in (root / "images", root / "assets" / "img"):
        if not folder.is_dir():
            continue
        for path in folder.rglob("*"):
            if path.is_file() and path.suffix.lower() in {".jpg", ".jpeg", ".png", ".gif", ".webp", ".svg", ".avif"}:
                found.append(path.relative_to(root).as_posix())
    return sorted(found)


def build_manifest(root: Path) -> dict:
    """Record every image. Licence stays null unless a real grant is already on file."""
    credits: dict[str, dict] = {}
    for path in iter_html(root):
        rel = path.relative_to(root).as_posix()
        html = path.read_text(encoding="utf-8", errors="replace")
        parser = PageParser()
        parser.feed(html)
        parser.close()
        for img_i, attrs in enumerate(parser.imgs):
            src = attrs.get("src", "")
            if not src:
                continue
            resolved = resolve_src(src, rel)
            if resolved.lower().startswith(("http://", "https://", "data:")):
                continue
            slot = credits.setdefault(resolved, {"alts": [], "pages": []})
            alt = collapse(attrs.get("alt", ""))
            caption = caption_after(html, img_i)
            text = alt
            if caption and caption not in alt:
                text = collapse(f"{alt} {caption}") if alt else caption
            if text and text not in slot["alts"]:
                slot["alts"].append(text)
            if rel not in slot["pages"]:
                slot["pages"].append(rel)
    images = []
    for rel in image_files(root):
        slot = credits.get(rel, {"alts": [], "pages": []})
        credit = " | ".join(slot["alts"])[:1200] if slot["alts"] else None
        images.append(
            {
                "path": rel,
                "status": "HOLD",
                "licence": None,
                "credit": credit,
                "credit_pages": slot["pages"][:12],
                "synthetic": None,
                "hold_reason": (
                    "No documented licence, rights grant, creator contract, or embedded "
                    "copyright metadata is in the repo. Credit text already on the pages "
                    "is copied here and is not treated as a licence. The licence was not guessed."
                ),
            }
        )
    return {
        "site": SITE,
        "note": (
            "Every image file under images/ and assets/img/. status HOLD means do not "
            "publish a new use of this file. A documented row needs status other than "
            "HOLD and a non empty licence string. synthetic null means the repo does "
            "not label the file as AI."
        ),
        "images": images,
    }


def reason_for(path: str, findings: list[Finding]) -> str:
    parts = []
    images = [item for item in findings if item.rule == "3"]
    if images:
        parts.append(
            f"{len(images)} image file(s) on this page have no documented licence. "
            "Credit text already on the page was copied into the image licence manifest. "
            "No licence was guessed. Status is HOLD."
        )
    if any(item.rule == "4" for item in findings):
        parts.append("This page has a factual claim section and no off site source URL.")
    terms = sorted({item.key for item in findings if item.rule == "6"})
    if terms:
        parts.append(
            "Election term screen matched " + ", ".join(terms) + ". Live wording was not changed."
        )
    extra = EXTRA_REASON.get(path)
    if extra:
        parts.append(extra)
    parts.append(
        "Allowlisted for this sha256 only. Not an approval by Joshua. A changed file is checked again."
    )
    return " ".join(parts)


def hold_paths(data: dict) -> list[str]:
    raw = data.get("paths", []) if isinstance(data, dict) else []
    return [str(item).replace("\\", "/").lstrip("./") for item in raw]


def path_is_held(rel: str, paths: list[str]) -> bool:
    for item in paths:
        if item.endswith("/") and rel.startswith(item):
            return True
        if rel == item:
            return True
    return False


def approvals_list(data: dict) -> list[dict]:
    raw = data.get("approvals", []) if isinstance(data, dict) else []
    return [item for item in raw if isinstance(item, dict)]


def hold_approved(rel: str, digest: str, approvals: list[dict]) -> bool:
    for item in approvals:
        if item.get("path") != rel:
            continue
        if str(item.get("sha256", "")).lower() != digest.lower():
            continue
        if item.get("approver") == "Joshua":
            return True
    return False


def exemption_keys(baseline: dict, rel: str, digest: str) -> set[tuple[str, str]]:
    keys: set[tuple[str, str]] = set()
    for page in baseline.get("pages", []) if isinstance(baseline, dict) else []:
        if page.get("path") != rel:
            continue
        if str(page.get("sha256", "")).lower() != digest.lower():
            continue
        for item in page.get("exemptions", []):
            keys.add((str(item.get("rule")), str(item.get("key"))))
    return keys


def is_blocking(finding: Finding, exempt: set[tuple[str, str]], approved: bool) -> bool:
    if finding.force_block:
        return True
    if not finding.published:
        return False
    if finding.rule == "8":
        return True
    if finding.rule == "HOLD_REVIEW":
        return not approved
    return (finding.rule, finding.key) not in exempt


def queue_suggestion(finding: Finding, exempted: bool) -> str:
    if finding.published and exempted:
        return (
            finding.suggestion
            + " Existing live page left unchanged and recorded in the baseline allowlist for this sha256 only. Not an approval."
        )
    if not finding.published:
        return finding.suggestion + " File is outside the published tree. Keep it unpublished."
    return finding.suggestion


def append_queue(root: Path, rows: list[dict]) -> int:
    path = root / "content-review" / "queue.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    existing: set[tuple[str, str, str]] = set()
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                continue
            existing.add((item.get("draft_path", ""), item.get("rule", ""), item.get("flagged", "")))
    added = 0
    with path.open("a", encoding="utf-8") as handle:
        for row in rows:
            marker = (row["draft_path"], row["rule"], row["flagged"])
            if marker in existing:
                continue
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
            existing.add(marker)
            added += 1
    return added


def evaluate(root: Path, *, write_queue: bool = False, ignore_baseline: bool = False, now: datetime | None = None) -> Outcome:
    root = root.resolve()
    outcome = Outcome()
    manifest_path = root / "content-review" / "image-licences.json"
    holds_path = root / "content-review" / "legal-holds.json"
    approvals_path = root / "content-review" / "approvals.json"
    baseline_path = root / "content-review" / "baseline-allowlist.json"
    if not manifest_path.is_file():
        outcome.missing_config.append(manifest_path.name)
    if not holds_path.is_file():
        outcome.missing_config.append(holds_path.name)
    manifest = load_json(manifest_path, {"images": []}) if manifest_path.is_file() else {"images": []}
    holds = hold_paths(load_json(holds_path, {"paths": []}) if holds_path.is_file() else {"paths": []})
    approvals = approvals_list(load_json(approvals_path, {"approvals": []}) if approvals_path.is_file() else {"approvals": []})
    baseline = {"pages": []} if ignore_baseline or not baseline_path.is_file() else load_json(baseline_path, {"pages": []})

    if manifest_path.name in outcome.missing_config:
        outcome.findings.append(
            Finding(
                path="content-review/image-licences.json",
                rule="3",
                key="manifest-missing",
                flagged="image licence manifest is missing",
                suggestion=SUGGESTIONS["3"],
                sources=[],
                title="image licence manifest",
                published=True,
                force_block=True,
            )
        )
    if holds_path.name in outcome.missing_config:
        outcome.findings.append(
            Finding(
                path="content-review/legal-holds.json",
                rule="8",
                key="blocklist-missing",
                flagged="legal hold blocklist is missing",
                suggestion=SUGGESTIONS["8"],
                sources=[],
                title="legal hold blocklist",
                published=True,
                force_block=True,
            )
        )

    for path in iter_html(root):
        rel = path.relative_to(root).as_posix()
        html = path.read_text(encoding="utf-8", errors="replace")
        findings, notes = analyze_html(html, rel, manifest)
        outcome.notes.extend(notes)
        digest = sha256_file(path)
        exempt = exemption_keys(baseline, rel, digest)
        approved = hold_approved(rel, digest, approvals)
        if path_is_held(rel, holds):
            title = findings[0].title if findings else rel
            sources = findings[0].sources if findings else []
            findings.append(
                Finding(
                    path=rel,
                    rule="8",
                    key=rel,
                    flagged=f"Blocklist path {rel}",
                    suggestion=SUGGESTIONS["8"],
                    sources=sources,
                    title=title,
                    published=publication_state(rel) == "published",
                )
            )
        for finding in findings:
            outcome.findings.append(finding)
            if is_blocking(finding, exempt, approved):
                outcome.blocking.append(finding)
            elif finding.published and finding.rule not in {"8", "HOLD_REVIEW"}:
                outcome.exempted.append(finding)

    if write_queue:
        moment = now or datetime.now(timezone.utc)
        ts = moment.strftime("%Y-%m-%dT%H:%M:%SZ")
        rows = []
        exempted_ids = {(item.path, item.rule, item.key) for item in outcome.exempted}
        for finding in outcome.findings:
            exempted = (finding.path, finding.rule, finding.key) in exempted_ids
            rows.append(finding.queue_obj(ts, queue_suggestion(finding, exempted)))
        append_queue(root, rows)
    return outcome


def write_baseline(root: Path, outcome: Outcome) -> dict:
    grouped: dict[str, list[Finding]] = {}
    for finding in outcome.findings:
        if not finding.published or finding.rule in {"8", "HOLD_REVIEW"} or finding.force_block:
            continue
        grouped.setdefault(finding.path, []).append(finding)
    pages = []
    for rel in sorted(grouped):
        findings = grouped[rel]
        digest = sha256_file(root / rel)
        exemptions = [
            {"rule": item.rule, "key": item.key}
            for item in sorted(findings, key=lambda item: (item.rule, item.key))
        ]
        # Unique by rule+key while keeping order.
        deduped = []
        seen = set()
        for item in exemptions:
            marker = (item["rule"], item["key"])
            if marker in seen:
                continue
            seen.add(marker)
            deduped.append(item)
        pages.append(
            {
                "path": rel,
                "sha256": digest,
                "exemptions": deduped,
                "reason": reason_for(rel, findings),
            }
        )
    payload = {
        "site": SITE,
        "audited": "2026-10-27",
        "note": (
            "Each page entry exempts only the listed rule keys while the file sha256 "
            "still matches. It is not an approval by Joshua. Rule 8 and HOLD_REVIEW "
            "are never exempted. A changed file is checked in full."
        ),
        "pages": pages,
    }
    path = root / "content-review" / "baseline-allowlist.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return payload


def format_report(outcome: Outcome) -> str:
    lines = [
        f"findings {len(outcome.findings)}",
        f"blocking {len(outcome.blocking)}",
        f"exempted {len(outcome.exempted)}",
        f"suppressed {len(outcome.notes)}",
        f"missing_config {','.join(outcome.missing_config) if outcome.missing_config else 'none'}",
    ]
    for finding in outcome.blocking:
        lines.append(f"BLOCK {finding.path} rule {finding.rule} {finding.flagged}")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Legal hold gate for noravellestays.com")
    parser.add_argument("--root", default=".", help="Repository root")
    parser.add_argument("--ci", action="store_true", help="Scan the repo and fail on blocking items")
    parser.add_argument("--write-manifest", action="store_true", help="Rewrite the image licence manifest")
    parser.add_argument("--write-baseline", action="store_true", help="Rewrite the baseline allowlist and queue")
    parser.add_argument("--no-queue", action="store_true", help="Do not append queue.jsonl")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    if args.write_manifest:
        payload = build_manifest(root)
        dest = root / "content-review" / "image-licences.json"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {dest} images {len(payload['images'])}")
        if not args.write_baseline and not args.ci:
            return 0
    if args.write_baseline:
        outcome = evaluate(root, write_queue=False, ignore_baseline=True)
        payload = write_baseline(root, outcome)
        if not args.no_queue:
            moment = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            rows = []
            for finding in outcome.findings:
                allowlisted = (
                    finding.published
                    and not finding.force_block
                    and finding.rule not in {"8", "HOLD_REVIEW"}
                )
                rows.append(finding.queue_obj(moment, queue_suggestion(finding, allowlisted)))
            append_queue(root, rows)
        real_blocks = [
            item for item in outcome.blocking
            if item.force_block or item.rule in {"8", "HOLD_REVIEW"}
        ]
        print(format_report(outcome))
        print(f"baseline pages {len(payload['pages'])}")
        print(f"unallowlisted blocks {len(real_blocks)}")
        return 1 if real_blocks else 0
    outcome = evaluate(root, write_queue=not args.no_queue)
    print(format_report(outcome))
    return 1 if outcome.blocking or outcome.missing_config else 0


if __name__ == "__main__":
    sys.exit(main())
